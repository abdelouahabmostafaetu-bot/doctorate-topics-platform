import type {
  CompetitionFormat,
  CompetitionLevel,
  CompetitionParticipation,
  CompetitionScope,
  WorldCompetition,
} from "./world-competitions"

const olympiadSubjects = ["algebra", "geometry", "number-theory", "combinatorics"]

const years = (from: number, to: number) =>
  Array.from({ length: to - from + 1 }, (_, index) => from + index).reverse()

type ArchiveCompetitionSeed = {
  slug: string
  shortName: string
  name: string
  nameAr: string
  descriptionAr: string
  level?: CompetitionLevel
  scope?: CompetitionScope
  format?: CompetitionFormat
  participation?: CompetitionParticipation
  region: string
  country?: string
  officialUrl: string
  archiveUrl: string
  languages: string[]
  subjects?: string[]
  editionYears: number[]
  assetMatch?: string
  assetExclude?: string[]
}

function archiveCompetition(seed: ArchiveCompetitionSeed): WorldCompetition {
  const subjects = seed.subjects ?? olympiadSubjects
  return {
    slug: seed.slug,
    shortName: seed.shortName,
    name: seed.name,
    nameAr: seed.nameAr,
    descriptionAr: seed.descriptionAr,
    level: seed.level ?? "secondary",
    scope: seed.scope ?? "national",
    format: seed.format ?? "olympiad",
    participation: seed.participation ?? "individual",
    region: seed.region,
    country: seed.country,
    officialUrl: seed.officialUrl,
    languages: seed.languages,
    subjects,
    editions: seed.editionYears.map((year) => ({
      year,
      title: `${seed.shortName} ${year} — Official Archive`,
      languages: seed.languages,
      subjects,
      officialProblemsUrl: seed.archiveUrl,
      assetMatch: seed.assetMatch,
      assetExclude: seed.assetExclude,
      mirrorPolicy: "link-only",
      published: true,
    })),
  }
}

